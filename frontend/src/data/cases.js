export function getCase(slug) {
  return cases.find((item) => item.slug === slug) || null
}

export function nextCase(slug) {
  const index = cases.findIndex((item) => item.slug === slug)
  return cases[(index + 1) % cases.length]
}

const numberFormat = new Intl.NumberFormat('ru-RU')

/** Число метрики в виде строки: «+65%», «26 961», «350 тыс ₽» */
export function formatMetric(metric, value = metric.value) {
  return `${metric.prefix || ''}${numberFormat.format(value)}${metric.suffix || ''}`
}

/** CSS-переменные палитры кейса */
export function caseThemeVars(item) {
  const t = item.theme
  return {
    '--case-bg': t.bg,
    '--case-ink': t.ink,
    '--case-accent': t.accent,
    '--case-accent-2': t.accent2,
  }
}
